package com.gaur.friendstogether.entity;

import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDateTime;

/**
 * =============================================================================
 * PaymentWebhookLog
 * =============================================================================
 *
 * This table stores every webhook event received from any payment gateway.
 *
 * Supported Providers
 * ---------------------------------------------------------------------------
 * ✔ Razorpay
 * ✔ Stripe
 * ✔ Google Play
 * ✔ Apple
 * ✔ PayPal
 *
 * ----------------------------------------------------------------------------
 * WHY THIS TABLE EXISTS?
 * ----------------------------------------------------------------------------
 *
 * 1. Prevent Duplicate Processing (Idempotency)
 *
 * Sometimes payment gateways send the same webhook multiple times.
 *
 * Example
 *
 * payment.captured
 * payment.captured
 * payment.captured
 *
 * Coins must be credited ONLY ONCE.
 *
 * ----------------------------------------------------------------------------
 *
 * 2. Audit
 *
 * Every webhook request should be permanently stored.
 *
 * ----------------------------------------------------------------------------
 *
 * 3. Debugging
 *
 * If customer says:
 *
 * "Payment successful but coins not received"
 *
 * We can inspect the original webhook payload.
 *
 * ----------------------------------------------------------------------------
 *
 * 4. Replay Support
 *
 * If server crashes while processing webhook,
 * this table helps replay pending events safely.
 *
 * ----------------------------------------------------------------------------
 *
 * IMPORTANT
 *
 * This Entity DOES NOT
 *
 * ❌ Verify Signature
 * ❌ Credit Wallet
 * ❌ Update WalletTransaction
 * ❌ Change Payment Status
 *
 * These responsibilities belong to Service Layer.
 *
 * =============================================================================
 */

@Entity
@Table(
        name = "payment_webhook_logs",
        indexes = {

                /**
                 * Find webhook by Payment.
                 */
                @Index(
                        name = "idx_webhook_payment",
                        columnList = "payment_id"
                ),

                /**
                 * Search by Gateway Event ID.
                 */
                @Index(
                        name = "idx_webhook_event",
                        columnList = "gateway_event_id",
                        unique = true
                ),

                /**
                 * Search by Provider.
                 */
                @Index(
                        name = "idx_webhook_provider",
                        columnList = "provider"
                ),

                /**
                 * Search by Processing Status.
                 */
                @Index(
                        name = "idx_webhook_status",
                        columnList = "status"
                )
        }
)

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class PaymentWebhookLog {

    /**
     * =========================================================================
     * INTERNAL DATABASE ID
     * =========================================================================
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * =========================================================================
     * PAYMENT
     * =========================================================================
     *
     * Every webhook belongs to one Payment.
     *
     * Relationship
     *
     * CoinOrder
     *      ↓
     * Payment
     *      ↓
     * WebhookLog
     *
     * One Payment
     * ↓
     * Many Webhook Events
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
            name = "payment_id",
            nullable = false
    )
    private Payment payment;

    /**
     * =========================================================================
     * PAYMENT PROVIDER
     * =========================================================================
     *
     * Identifies which payment gateway sent this webhook.
     *
     * Example
     *
     * RAZORPAY
     * STRIPE
     * GOOGLE_PLAY
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentProvider provider;

    /**
     * =========================================================================
     * GATEWAY EVENT ID
     * =========================================================================
     *
     * Unique identifier generated by payment gateway.
     *
     * Examples
     *
     * Razorpay
     * evt_29ASD82J...
     *
     * Stripe
     * evt_3Oj4....
     *
     * Service Layer Responsibility
     * ----------------------------
     * ✔ Perform Idempotency Check
     * ✔ Reject Duplicate Events
     *
     * Database Responsibility
     * -----------------------
     * ✔ UNIQUE Constraint
     */
    @Column(
            name = "gateway_event_id",
            nullable = false,
            unique = true,
            updatable = false,
            length = 150
    )
    private String gatewayEventId;

    /**
     * =========================================================================
     * WEBHOOK EVENT TYPE
     * =========================================================================
     *
     * Examples
     *
     * PAYMENT_CAPTURED
     * PAYMENT_FAILED
     * ORDER_PAID
     * REFUND_PROCESSED
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private WebhookEventType eventType;

    /**
     * =========================================================================
     * GATEWAY SIGNATURE
     * =========================================================================
     *
     * Raw signature received from payment gateway.
     *
     * Service Layer will verify this signature before
     * processing the webhook.
     */
    @Column(length = 500)
    private String gatewaySignature;

    /**
     * =========================================================================
     * RAW WEBHOOK PAYLOAD
     * =========================================================================
     *
     * Stores complete webhook JSON exactly as received.
     *
     * Useful For
     *
     * ✔ Audit
     * ✔ Debugging
     * ✔ Replay
     * ✔ Customer Support
     */
    @Lob
    @Basic(fetch = FetchType.LAZY)
    private String payload;
    /**
     * =========================================================================
     * WEBHOOK PROCESSING STATUS
     * =========================================================================
     *
     * Indicates whether this webhook has already been processed.
     *
     * Example Flow
     *
     * RECEIVED
     *      ↓
     * PROCESSING
     *      ↓
     * PROCESSED
     *
     * OR
     *
     * FAILED
     *
     * Service Layer Responsibility
     * -------------------------------------------------------------------------
     * ✔ Update processing status
     * ✔ Retry failed webhooks
     * ✔ Skip already processed webhooks
     */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(nullable = false)
    private WebhookStatus status = WebhookStatus.RECEIVED;

    /**
     * =========================================================================
     * FAILURE REASON
     * =========================================================================
     *
     * Stores failure reason if webhook processing fails.
     *
     * Examples
     *
     * Invalid Signature
     * Payment Not Found
     * Wallet Update Failed
     * Database Error
     * Duplicate Event
     *
     * Service Layer Responsibility
     * -------------------------------------------------------------------------
     * Populate only when processing fails.
     */
    @Column(length = 1000)
    private String failureReason;

    /**
     * =========================================================================
     * WEBHOOK RECEIVED TIME
     * =========================================================================
     *
     * Time when webhook request reached our backend.
     */
    @Column(nullable = false, updatable = false)
    private LocalDateTime receivedAt;

    /**
     * =========================================================================
     * WEBHOOK PROCESSED TIME
     * =========================================================================
     *
     * Time when webhook processing completed successfully.
     *
     * Null means webhook has not yet been processed.
     */
    private LocalDateTime processedAt;

    /**
     * =========================================================================
     * PRE PERSIST
     * =========================================================================
     *
     * Automatically executed before INSERT.
     *
     * NOTE
     * -------------------------------------------------------------------------
     * Service Layer Responsibilities
     *
     * ✔ Verify Gateway Signature
     * ✔ Perform Idempotency Check
     * ✔ Find Related Payment
     * ✔ Update Payment Status
     * ✔ Credit Wallet
     * ✔ Create WalletTransaction
     * ✔ Mark Webhook as Processed
     *
     * Entity only stores webhook information.
     */
    @PrePersist
    protected void onCreate() {

        receivedAt = LocalDateTime.now();
    }

}
