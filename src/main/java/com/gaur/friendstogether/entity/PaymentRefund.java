package com.gaur.friendstogether.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * ======================================================================
 * PaymentRefund
======================================================================
 *
 * Stores every refund initiated against a Payment.
 *
 * -----------------------------------------------------------------------------
 * IMPORTANT
 * -----------------------------------------------------------------------------
 *
 * PaymentRefund is NOT responsible for:
 *
 * ❌ Updating Wallet Balance
 * ❌ Creating WalletTransaction
 * ❌ Updating Payment Status
 *
 * These responsibilities belong to the Service Layer.
 *
 * -----------------------------------------------------------------------------
 *
 * This table only stores refund information received
 * from Payment Gateway.
 *
 * -----------------------------------------------------------------------------
 *
 * Typical Flow
 *
 * Payment
 *      │
 *      ▼
 * Refund Requested
 *      │
 *      ▼
 * Gateway Refund
 *      │
 *      ▼
 * PaymentRefund Created
 *      │
 *      ▼
 * Webhook Received
 *      │
 *      ▼
 * WalletTransaction (Reverse Entry)
 *
 * -----------------------------------------------------------------------------
 *
 * Service Layer Responsibilities
 *
 * ✔ Generate Refund Reference
 * ✔ Call Payment Gateway API
 * ✔ Verify Refund Webhook
 * ✔ Update Refund Status
 * ✔ Create Reverse WalletTransaction
 * ✔ Reverse Coins (If Applicable)
 *
 * ======================================================================
 */

@Entity
@Table(
        name = "payment_refunds",
        indexes = {

                /**
                 * Search Refunds by Payment.
                 */
                @Index(
                        name = "idx_refund_payment",
                        columnList = "payment_id"
                ),

                /**
                 * Search Refunds by Gateway Refund ID.
                 */
                @Index(
                        name = "idx_gateway_refund",
                        columnList = "gateway_refund_id",
                        unique = true
                ),

                /**
                 * Search Refunds by Status.
                 */
                @Index(
                        name = "idx_refund_status",
                        columnList = "status"
                )
        }
)

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class PaymentRefund {

    /**
     * ======================================================================
     * INTERNAL DATABASE ID     ======================================================================
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * ======================================================================
     * BUSINESS REFUND NUMBER
======================================================================
     *
     * Example
     *
     * REF-2026-00000001
     *
     * Generated by Service Layer.
     *
     * Database validates uniqueness only.
     */
    @Column(
            nullable = false,
            unique = true,
            updatable = false,
            length = 50
    )
    private String refundNumber;

    /**
     * ======================================================================
     * ORIGINAL PAYMENT
======================================================================
     *
     * Refund always belongs to a Payment.
     *
     * One Payment
     * ↓
     * Multiple Refunds
     *
     * Supports Partial Refunds.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
            name = "payment_id",
            nullable = false
    )
    private Payment payment;

    /**
     * ======================================================================
     * PAYMENT PROVIDER ======================================================================
     *
     * Example
     *
     * Razorpay
     * Stripe
     * Google Play
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentProvider provider;

    /**
     * ======================================================================
     * GATEWAY REFUND ID ======================================================================
     *
     * Unique refund identifier generated by payment gateway.
     *
     * Example
     *
     * Razorpay
     * rfnd_P9A82...
     *
     * Stripe
     * re_xxxxxx
     */
    @Column(
            name = "gateway_refund_id",
            unique = true,
            length = 150
    )
    private String gatewayRefundId;

    /**
     * ======================================================================
     * REFUND AMOUNT ======================================================================
     *
     * Supports:
     *
     * Full Refund
     * Partial Refund
     */
    @Column(
            nullable = false,
            precision = 10,
            scale = 2
    )
    private BigDecimal refundAmount;

    /**
     * ======================================================================
     * CURRENCY ======================================================================
     *
     * Snapshot of refund currency.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CurrencyType currency;
    /**
     * ======================================================================
     * REFUND STATUS ======================================================================
     *
     * Represents current lifecycle of refund.
     *
     * Example Flow
     *
     * REQUESTED
     *      ↓
     * PROCESSING
     *      ↓
     * COMPLETED
     *
     * OR
     *
     * FAILED
     * CANCELLED
     *
     * Service Layer Responsibility
     * -------------------------------------------------------------------------
     * ✔ Update refund status
     * ✔ Retry failed refunds
     * ✔ Handle webhook updates
     */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(nullable = false)
    private RefundStatus status = RefundStatus.REQUESTED;

    /**
     * ======================================================================
     * REFUND REASON ======================================================================
     *
     * Standard business reason for refund.
     *
     * Example
     *
     * CUSTOMER_REQUEST
     * DUPLICATE_PAYMENT
     * PAYMENT_FAILURE
     * FRAUD_DETECTED
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private RefundReason refundReason;

    /**
     * ======================================================================
     * REMARKS ======================================================================
     *
     * Optional business remarks.
     *
     * Example
     *
     * Customer accidentally paid twice.
     * Payment captured but service failed.
     *
     * Service Layer Responsibility
     * -------------------------------------------------------------------------
     * Populate when additional explanation is required.
     */
    @Column(length = 1000)
    private String remarks;

    /**
     * ======================================================================
     * FAILURE REASON ======================================================================
     *
     * Populated only when refund processing fails.
     *
     * Examples
     *
     * Gateway timeout
     * Invalid payment
     * Refund window expired
     * Gateway rejected refund
     */
    @Column(length = 1000)
    private String failureReason;

    /**
     * ======================================================================
     * REFUND REQUEST TIME ======================================================================
     *
     * Time when refund request was initiated.
     */
    @Column(nullable = false, updatable = false)
    private LocalDateTime requestedAt;

    /**
     * ======================================================================
     * REFUND COMPLETION TIME ======================================================================
     *
     * Time when gateway confirmed refund success.
     *
     * Null means refund is still pending.
     */
    private LocalDateTime completedAt;

    /**
     * ======================================================================
     * RECORD CREATED TIME ======================================================================
     */
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * ======================================================================
     * LAST UPDATED TIME ======================================================================
     */
    @Column(nullable = false)
    private LocalDateTime updatedAt;

    /**
     * ======================================================================
     * PRE PERSIST
======================================================================
     *
     * Automatically executed before INSERT.
     *
     * NOTE
     * -------------------------------------------------------------------------
     * Service Layer Responsibilities
     *
     * ✔ Generate Refund Number
     * ✔ Call Gateway Refund API
     * ✔ Validate Refund Eligibility
     * ✔ Populate Refund Reason
     * ✔ Store Gateway Refund ID
     * ✔ Create Reverse WalletTransaction (if required)
     * ✔ Reverse Coins (if applicable)
     * ✔ Update Payment Status
     *
     * Entity only stores refund information.
     */
    @PrePersist
    protected void onCreate() {

        requestedAt = LocalDateTime.now();
        createdAt = LocalDateTime.now();
        updatedAt = LocalDateTime.now();
    }

    /**
     * ======================================================================
     * PRE UPDATE
======================================================================
     *
     * Automatically updates modification timestamp.
     */
    @PreUpdate
    protected void onUpdate() {

        updatedAt = LocalDateTime.now();
    }

}
