package com.gaur.friendstogether.entity;
import jakarta.persistence.*;
import lombok.*;
import java.math.BigDecimal;
import java.time.LocalDateTime;
/**
 * =====================================================================
 * Payment
 * =====================================================================
 *
 * This table represents every payment attempt made by the user.
 *
 * IMPORTANT
 * ---------------------------------------------------------------------------
 *
 * CoinOrder != Payment
 *
 * CoinOrder
 * ----------
 * Represents WHAT the user wants to purchase.
 *
 * Example:
 * Starter Pack
 * ₹99
 * 100 Coins
 *
 *
 * Payment
 * --------
 * Represents HOW the user tried to pay.
 *
 * Example
 *
 * Attempt #1
 * Razorpay + Card
 * FAILED
 *
 * Attempt #2
 * Razorpay + UPI
 * SUCCESS
 *
 * Therefore,
 *
 * One CoinOrder
 *        |
 *        |-------> Many Payment Attempts
 *
 *
 * Payment table NEVER:
 *
 * ❌ Credits Coins
 * ❌ Updates Wallet
 * ❌ Gives Rewards
 *
 * Those responsibilities belong to:
 *
 * UserWallet
 * WalletTransaction
 *
 * ====================================================================
 */

@Entity
@Table(
        name = "payments",
        indexes = {

                /**
                 * Find all payment attempts of an order.
                 */
                @Index(
                        name = "idx_payment_order",
                        columnList = "order_id"
                ),

                /**
                 * Find payment by provider.
                 */
                @Index(
                        name = "idx_payment_provider",
                        columnList = "provider"
                ),

                /**
                 * Fast lookup using Gateway Order ID.
                 */
                @Index(
                        name = "idx_gateway_order",
                        columnList = "gateway_order_id"
                ),

                /**
                 * Fast lookup using Gateway Payment ID.
                 */
                @Index(
                        name = "idx_gateway_payment",
                        columnList = "gateway_payment_id"
                ),

                /**
                 * Search by payment status.
                 */
                @Index(
                        name = "idx_payment_status",
                        columnList = "status"
                )
        }
)

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Payment {

    /**
     * ======================================================================
     * INTERNAL DATABASE ID
     * ======================================================================
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * =====================================================================
     * BUSINESS PAYMENT REFERENCE
     * =====================================================================
     *
     * Human readable payment reference.
     *
     * Example
     *
     * PAY-2026-00000001
     *
     * Generated by application.
     *
     * Never expose database ID to users.
     */
    @Column(
            nullable = false,
            unique = true,
            updatable = false,
            length = 50
    )
    private String paymentReference;

    /**
     * =====================================================================
     * COIN ORDER
     * ======================================================================
     *
     * Which CoinOrder this payment belongs to.
     *
     * One Order
     * ↓
     * Multiple Payments
     *
     * Example
     *
     * Order
     * ↓
     * Card Failed
     *
     * Order
     * ↓
     * UPI Success
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
            name = "order_id",
            nullable = false
    )
    private CoinOrder order;

    /**
     * ======================================================================
     * PAYMENT PROVIDER
     * =====================================================================
     *
     * Example
     *
     * Razorpay
     * Stripe
     * Google Play
     * Apple
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentProvider provider;

    /**
     * =====================================================================
     * PAYMENT METHOD
     * =====================================================================
     *
     * Example
     *
     * UPI
     * CARD
     * NET BANKING
     * WALLET
     */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(nullable = false)
    private PaymentMethod paymentMethod = PaymentMethod.UNKNOWN;

    /**
     * =====================================================================
     * GATEWAY ORDER ID
     * =====================================================================
     *
     * Generated by payment gateway.
     *
     * Example
     *
     * Razorpay
     * order_QA84D...
     *
     * Stripe
     * pi_xxxxx
     */
    @Column(
            name = "gateway_order_id",
            length = 150
    )
    private String gatewayOrderId;

    /**
     * =====================================================================
     * GATEWAY PAYMENT ID
     * =====================================================================
     *
     * Generated after successful payment.
     *
     * Example
     *
     * pay_QA838383...
     */
    @Column(
            name = "gateway_payment_id",
            unique = true,
            length = 150
    )
    private String gatewayPaymentId;

    /**
     * =====================================================================
     * GATEWAY SIGNATURE
     * =====================================================================
     *
     * Used to verify payment authenticity.
     *
     * Coins should NEVER be credited
     * before successful signature verification.
     */
    @Column(
            name = "gateway_signature",
            length = 500
    )
    private String gatewaySignature;

    /**
     * =====================================================================
     * PAYMENT AMOUNT SNAPSHOT
     * =====================================================================
     *
     * Snapshot of payment amount.
     *
     * Future CoinPlan price changes
     * should never affect payment history.
     */
    @Column(
            nullable = false,
            precision = 10,
            scale = 2
    )
    private BigDecimal amount;

    /**
     * ======================================================================
     * PAYMENT CURRENCY
     * =====================================================================
     *
     * INR
     * USD
     * AED
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CurrencyType currency;

    /**
     * ======================================================================
     * PAYMENT STATUS
======================================================================
     *
     * Represents the current lifecycle of this payment.
     *
     * Example:
     *
     * CREATED
     * ↓
     * PENDING
     * ↓
     * AUTHORIZED
     * ↓
     * CAPTURED
     *
     * OR
     *
     * FAILED
     * CANCELLED
     * REFUNDED
     */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(nullable = false)
    private PaymentStatus status = PaymentStatus.CREATED;

    /**
     * ======================================================================
     * PAYMENT VERIFICATION STATUS
=====================================================================
     *
     * Even if payment is successful,
     * coins must NEVER be credited until
     * gateway signature verification succeeds.
     *
     * Example:
     *
     * Payment Success
     *        ↓
     * Verify Signature
     *        ↓
     * VERIFIED
     */
    @Enumerated(EnumType.STRING)
    @Builder.Default
    @Column(nullable = false)
    private PaymentVerificationStatus verificationStatus =
            PaymentVerificationStatus.PENDING;

    /**
     * =====================================================================
     * WALLET CREDIT FLAG
     * =====================================================================
     *
     * Prevents duplicate coin credit.
     *
     * Example:
     *
     * Payment Success
     * ↓
     * Coins Added
     * ↓
     * walletCredited = true
     *
     * If webhook comes again,
     * system checks this flag and skips
     * duplicate wallet credit.
     */
    @Builder.Default
    @Column(nullable = false)
    private boolean walletCredited = false;

    /**
     * ======================================================================
     * PAYMENT RETRY COUNT
     * ======================================================================
     *
     * Number of retry attempts made for this payment.
     *
     * Useful for:
     *
     * Analytics
     * Fraud Detection
     * Monitoring
     */
    @Builder.Default
    @Column(nullable = false)
    private Integer retryCount = 0;

    /**
     * =====================================================================
     * GATEWAY RESPONSE
     * =====================================================================
     *
     * Complete gateway response stored as JSON.
     *
     * Useful for:
     *
     * Debugging
     * Auditing
     * Customer Support
     */
    @Lob
    @Basic(fetch = FetchType.LAZY)
    private String gatewayResponse;

    /**
     * ======================================================================
     * GATEWAY ERROR CODE
     * =====================================================================
     *
     * Example:
     *
     * BAD_REQUEST
     * PAYMENT_FAILED
     * INVALID_SIGNATURE
     */
    @Column(length = 100)
    private String errorCode;

    /**
     * ======================================================================
     * ERROR DESCRIPTION
     * ======================================================================
     *
     * Human-readable error returned by the payment gateway.
     *
     * Example:
     *
     * Insufficient Balance
     * Invalid Card
     * Payment Cancelled
     */
    @Column(length = 1000)
    private String errorDescription;

    /**
     * =====================================================================
     * PAYMENT COMPLETION TIME
     * ======================================================================
     *
     * Time when payment became successful.
     *
     * Null means payment has not been completed yet.
     */
    private LocalDateTime completedAt;

    /**
     * ======================================================================
     * RECORD CREATED TIME
     * ======================================================================
     */
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * ======================================================================
     * LAST UPDATED TIME
     * ======================================================================
     */
    @Column(nullable = false)
    private LocalDateTime updatedAt;

    /**
     * =====================================================================
     * Automatically executed before INSERT.
     * ======================================================================
     */
    @PrePersist
    protected void onCreate() {

        createdAt = LocalDateTime.now();
        updatedAt = LocalDateTime.now();
    }

    /**
     * =====================================================================
     * Automatically executed before UPDATE.
     * =====================================================================
     */
    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }
}
